# Bundles js/modules/*.js + js/app.js into js/app.bundle.js (classic script, works from file://)
import re
order=['ui','storage','quiz-engine','kanji','vocab','grammar']
out=['/* generated by build.py - edit js/modules/*.js and js/app.js, then run: python3 build.py */','(function(){','const K=KANJI_320;']
def strip(s):
    s=re.sub(r"^import .*?;\s*$",'',s,flags=re.M)
    s=re.sub(r"^export (?=const|function|let)",'',s,flags=re.M)
    return s
for m in order: out.append(strip(open(f'js/modules/{m}.js',encoding='utf8').read()).replace("const K=KANJI_320;",''))
app=strip(open('js/app.js',encoding='utf8').read())
for a,b in [('kanji.counts','counts'),('kanji.nextSuggested','nextSuggested'),('kanji.index','index'),('kanji.detail','detail'),('kanji.flash','flash'),('kanji.quizMenu','quizMenu')]: app=app.replace(a,b)
out.append(app);out.append('window.__minna={VOCAB,vocabQs,grammarQs,GRAMMAR};');out.append('})();')
open('js/app.bundle.js','w',encoding='utf8').write('\n'.join(out))
d=open('js/data/kanji-320.js',encoding='utf8').read().replace('export const KANJI_320','const KANJI_320')
open('js/data/kanji-320.classic.js','w',encoding='utf8').write(d)
